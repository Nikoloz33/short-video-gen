"""Export the video contract as JSON Schema for the TypeScript codegen.

uv run python -m agent.schemas.export          # writes video/src/generated/spec.schema.json
uv run python -m agent.schemas.export --check  # exit 1 if the file is stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from agent.schemas.video_spec import VideoSpec
from agent.settings import get_settings


def schema_path() -> Path:
    return get_settings().video_dir / "src" / "generated" / "spec.schema.json"


def _strip_property_titles(node: Any) -> Any:
    """Drop the auto titles Pydantic puts on every field ("Duration S"): codegen would turn each one
    into a named TS type. Model titles (TitleCardScene, ...) stay — they name the generated types."""
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for k, v in node.items():
            if k == "properties":
                out[k] = {
                    p: _strip_property_titles({kk: vv for kk, vv in s.items() if kk != "title"})
                    for p, s in v.items()
                }
            else:
                out[k] = _strip_property_titles(v)
        return out
    if isinstance(node, list):
        return [_strip_property_titles(v) for v in node]
    return node


def video_spec_schema() -> dict[str, Any]:
    # Serialization mode: defaulted fields are required, matching what the agent always emits.
    schema: dict[str, Any] = _strip_property_titles(VideoSpec.model_json_schema(mode="serialization"))
    schema["$comment"] = "GENERATED by `uv run python -m agent.schemas.export` - do not edit"
    return schema


def render() -> str:
    return json.dumps(video_spec_schema(), indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the exported file is stale")
    args = parser.parse_args(argv)
    path = schema_path()
    text = render()
    if args.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            sys.stderr.write(f"stale: {path} (run `uv run python -m agent.schemas.export`)\n")
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    sys.stderr.write(f"wrote {path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
