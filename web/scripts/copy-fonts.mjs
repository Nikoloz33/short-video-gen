// Copies Noto Sans + Noto Sans Georgian (400-700) from @fontsource into web/public/fonts and writes
// fonts.css with unicode ranges — the UI uses local fonts only, never a CDN.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..', '..');
const dst = path.join(here, '..', 'public', 'fonts');
fs.mkdirSync(dst, { recursive: true });

const faces = [
  ['Noto Sans', 'noto-sans', 'latin'],
  ['Noto Sans', 'noto-sans', 'latin-ext'],
  ['Noto Sans Georgian', 'noto-sans-georgian', 'georgian'],
];
const css = ['/* Generated by scripts/copy-fonts.mjs — bundled locally, no CDN. */'];
for (const [family, pkg, subset] of faces) {
  const dir = path.join(root, 'node_modules', '@fontsource', pkg);
  for (const weight of [400, 500, 600, 700]) {
    const file = `${pkg}-${subset}-${weight}-normal.woff2`;
    const src = path.join(dir, 'files', file);
    if (!fs.existsSync(src)) continue;
    fs.copyFileSync(src, path.join(dst, file));
    const block = fs
      .readFileSync(path.join(dir, `${weight}.css`), 'utf8')
      .split('@font-face')
      .find((b) => b.includes(file));
    const range = block && /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    css.push(
      `@font-face{font-family:'${family}';font-style:normal;font-display:swap;font-weight:${weight};` +
        `src:url('/fonts/${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}`,
    );
  }
}
fs.copyFileSync(
  path.join(root, 'node_modules', '@fontsource', 'noto-sans', 'LICENSE'),
  path.join(dst, 'OFL.txt'),
);
fs.writeFileSync(path.join(here, '..', 'public', 'fonts.css'), css.join('\n') + '\n');
